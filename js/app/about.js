"use strict";
/* Settings → About: version, build/deploy dates, and the last two commits with their changes.
   BUILD_INFO is generated by scripts/build-info.mjs and is plain data, so this works offline. */
function renderAbout(){
  const info=self.BUILD_INFO||{};
  $('#aboutVersion').textContent='Bingo Caller v'+APP_VERSION;
  const fmt=iso=>iso ? new Date(iso).toLocaleString([], {year:'numeric',month:'short',day:'numeric',hour:'2-digit',minute:'2-digit'}) : '—';
  const day=iso=>iso ? new Date(iso).toLocaleDateString([], {year:'numeric',month:'short',day:'numeric'}) : '—';
  $('#aboutDates').textContent=`Built ${fmt(info.buildDate)} · Deployed ${day(info.deployDate)}`;
  const list=$('#aboutCommits');
  const commits=info.commits||[];
  list.innerHTML=commits.length ? commits.map(c=>`
    <li>
      <div class="c-subject">${esc(c.subject)}</div>
      <div class="c-meta mono">${esc(c.hash)} · ${esc(day(c.date))}</div>
      ${c.files&&c.files.length ? `<ul class="c-files">${c.files.map(f=>`<li><span class="mono">${esc(f.path)}</span> <span class="muted">${esc(f.change)}</span></li>`).join('')}</ul>` : ''}
    </li>`).join('') : '<li class="muted">No commit info bundled in this build.</li>';
}
