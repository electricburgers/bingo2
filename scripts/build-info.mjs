#!/usr/bin/env node
/* Generates the two files the app can't know at runtime (it has no build step):
 *   js/config/build-info.js  — build/deploy dates + the last two commit subjects
 *   js/config/precache.js    — every asset index.html loads, for sw.js to precache for offline use
 *
 * Usage:  node scripts/build-info.mjs [--pending "commit message"] [--deploy YYYY-MM-DD]
 *   --pending  include the commit you're about to make (read from the staged diff) as the newest
 *              entry, so the About panel lists it. Run it, `git add -A`, then commit.
 *   --deploy   deploy date shown next to the version (default: today). Build date is always "now".
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' });
const arg = n => { const i = process.argv.indexOf('--' + n); return i > -1 ? process.argv[i + 1] : null; };

function committed(rev) {
  const [hash, date, subject] = git('log', '-1', '--format=%h%x00%aI%x00%s', rev).trim().split('\0');
  return { hash, date, subject };
}

const pendingMsg = arg('pending');
const commits = [];
if (pendingMsg) {
  commits.push({
    hash: 'pending', date: new Date().toISOString(), subject: pendingMsg,
  });
  commits.push(committed('HEAD'));
} else {
  commits.push(committed('HEAD'), committed('HEAD~1'));
}

const now = new Date();
const deploy = arg('deploy') ? new Date(arg('deploy') + 'T12:00:00') : now;
const info = { buildDate: now.toISOString(), deployDate: deploy.toISOString(), commits };
writeFileSync(join(root, 'js/config/build-info.js'),
  `"use strict";\n/* GENERATED by scripts/build-info.mjs — do not edit. */\nself.BUILD_INFO = ${JSON.stringify(info, null, 2)};\n`);

// Precache list: everything index.html pulls in, plus the entry points themselves.
const html = readFileSync(join(root, 'index.html'), 'utf8');
const assets = [...html.matchAll(/<(?:script|link)\b[^>]*?(?:src|href)="([^"]+)"/g)]
  .map(m => m[1]).filter(u => !/^(?:https?:)?\/\//.test(u) && !u.startsWith('data:'));
const urls = [...new Set(['./', 'index.html', ...assets, 'sw.js'])].map(u => (u === './' ? u : './' + u));
writeFileSync(join(root, 'js/config/precache.js'),
  `"use strict";\n/* GENERATED by scripts/build-info.mjs from index.html — do not edit. */\nself.PRECACHE_URLS = ${JSON.stringify(urls, null, 2)};\n`);

console.log(`build-info: ${commits.map(c => c.hash).join(', ')} · ${urls.length} precached URLs`);
